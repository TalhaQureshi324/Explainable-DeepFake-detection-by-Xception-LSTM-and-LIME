-- Phase 4A: initial schema — analyses, windows, artifacts, model versions, jobs
-- Apply in the Supabase SQL editor or via `supabase db push`.
-- The local development backend (backend/app/persistence/sqlite_repository.py)
-- mirrors this schema exactly in SQLite so the app runs without credentials.

-- =============== model registry (immutable history) ===============
create table if not exists model_versions (
  id uuid primary key default gen_random_uuid(),
  version text not null unique,                -- "v1" | "v2" | future "v3"
  name text not null,                          -- "Xception-LSTM"
  checkpoint_sha256 text not null,
  input_frames integer not null,
  input_size integer not null,
  preprocessing_version text not null,         -- e.g. "dnn-ellipse-01"
  notes text,
  created_at timestamptz not null default now()
);
comment on table model_versions is
  'Immutable checkpoint registry: historical reports keep their own copies of
   version + hash, so edits here never rewrite history.';

-- =============== analyses (one row per submitted media) ===============
create table if not exists analyses (
  id uuid primary key,                         -- generated by the backend (uuid4)
  user_id uuid references auth.users(id) on delete cascade,   -- null = guest (ephemeral)
  media_type text not null check (media_type in ('video', 'image')),
  filename text not null,
  size_bytes bigint,
  sha256 text,
  width integer, height integer,
  fps double precision, duration_seconds double precision,
  frames_extracted integer, frames_analyzed integer, valid_face_detections integer,
  status text not null default 'QUEUED'
    check (status in ('QUEUED','PREPROCESSING','INFERENCING','EXPLAINING',
                      'GENERATING_REPORT','COMPLETED','FAILED')),
  model_name text, model_version text, checkpoint_sha256 text,
  input_frames integer, input_size integer,
  label text check (label in ('REAL', 'FAKE')),
  fake_score double precision,
  threshold double precision, threshold_version text,
  prediction_method text, score_is_calibrated boolean default false,
  processing_duration_seconds double precision,
  error_code text, error text,
  warnings jsonb not null default '[]'::jsonb,
  explainability jsonb not null default '{}'::jsonb,
  result_json jsonb,                           -- final structured API response snapshot
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz,
  retained_until timestamptz                   -- retention sweeper hint
);
create index if not exists analyses_user_created_idx
  on analyses (user_id, created_at desc);
create index if not exists analyses_status_idx on analyses (status);
create index if not exists analyses_label_idx on analyses (label);

-- =============== per-window scores (real timeline) ===============
create table if not exists analysis_windows (
  id uuid primary key default gen_random_uuid(),
  analysis_id uuid not null references analyses(id) on delete cascade,
  window_index integer not null,
  label text not null,
  score double precision not null,
  frame_start integer, frame_end integer,      -- ORIGINAL video frame indices
  start_seconds double precision, end_seconds double precision,
  created_at timestamptz not null default now(),
  unique (analysis_id, window_index)
);
create index if not exists analysis_windows_analysis_idx
  on analysis_windows (analysis_id, window_index);

-- =============== artifacts (private storage paths) ===============
create table if not exists analysis_artifacts (
  id uuid primary key default gen_random_uuid(),
  analysis_id uuid not null references analyses(id) on delete cascade,
  kind text not null check (kind in ('face_preview', 'lime', 'timeline', 'pdf', 'upload')),
  storage_path text not null,                  -- bucket-internal path, never a filesystem path
  bucket text not null,                        -- analysis-artifacts | analysis-uploads | analysis-reports
  created_at timestamptz not null default now(),
  unique (analysis_id, kind, storage_path)
);
create index if not exists analysis_artifacts_analysis_idx
  on analysis_artifacts (analysis_id);

-- =============== durable job queue ===============
create table if not exists analysis_jobs (
  id uuid primary key default gen_random_uuid(),
  analysis_id uuid not null unique references analyses(id) on delete cascade,
  state text not null default 'QUEUED'
    check (state in ('QUEUED','RUNNING','COMPLETED','FAILED','DEAD')),
  attempts integer not null default 0,
  max_attempts integer not null default 3,
  lease_until timestamptz,                     -- worker lease; null/Expired => claimable
  worker_id text,
  error_kind text check (error_kind in ('recoverable', 'permanent', null)),
  last_error text,
  run_after timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists analysis_jobs_claim_idx
  on analysis_jobs (state, run_after) where state = 'QUEUED';
